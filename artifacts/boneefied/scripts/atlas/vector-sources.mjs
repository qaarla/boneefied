import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const assets = join(root, 'assets/images/anatomy');
const rows = [];
function walk(folder) {
  for (const entry of readdirSync(folder, { withFileTypes: true })) {
    const file = join(folder, entry.name);
    if (entry.isDirectory()) walk(file);
    else if (entry.name.endsWith('.svg')) {
      const png = folder.endsWith('/foundations-corrections')
        ? join(assets, entry.name.replace(/\.svg$/, '.png'))
        : file.replace(/\.svg$/, '.png');
      if (existsSync(png)) rows.push({ png: relative(root, png), svg: relative(root, file) });
    }
  }
}
walk(assets);
rows.sort((a, b) => a.png.localeCompare(b.png));
const code = `/** Generated by scripts/atlas/vector-sources.mjs. Exact local masters, lazy XML loading.
 * Keyed by the existing PNG module so every alias, lesson and practice path keeps
 * its image identity, aspect ratio, annotation coordinates and photo companions.
 */
const vectorSources = new Map<number, () => string>([
${rows.map(({ png, svg }) => `  [require('@/${png}'), () => require('@/${svg}') as string],`).join('\n')}
]);

export function vectorXmlForSource(source?: number): string | undefined {
  return source ? vectorSources.get(source)?.() : undefined;
}
`;
export function generateVectorSources() {
  writeFileSync(join(root, 'content/vector-image-sources.generated.ts'), code);
  console.log(`Registered ${rows.length} exact SVG/PNG source pairs.`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generateVectorSources();
